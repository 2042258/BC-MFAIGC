"""Export paper-ready LaTeX tables from the collected reports."""

from __future__ import annotations
import argparse
import json
from pathlib import Path

METHODS = {
    "bc1_def1": "BC-MFAIGC",
    "bc0_def1": "No-chain + filter",
    "bc0_def0": "Plain FedAvg",
}
RATIOS = {0: "0\\%", 1: "10\\%", 3: "30\\%", 6: "60\\%"}


def fmt(value, digits=3, dash="--"):
    return dash if value is None else f"{value:.{digits}f}"


def pm(entry, digits=3):
    if not entry or entry["mean"] is None:
        return "--"
    if entry["n"] > 1:
        return f"{entry['mean']:.{digits}f} $\\pm$ {entry['std']:.{digits}f}"
    return f"{entry['mean']:.{digits}f}"


def main(*, project_root=None) -> None:
    project_root = Path.cwd() if project_root is None else Path(project_root)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--reports",
        type=Path,
        default=project_root / "phase1_validation/reports/final_reports.json",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=project_root / "phase1_validation/reports/latex_tables.tex",
    )
    args = parser.parse_args()
    reports = json.loads(args.reports.read_text())
    detection = reports["detection"]
    fid = reports["fid"]
    timing = reports["timing_single_tenant"]
    final_federated = reports["figures"]["final_federated"]
    final_central = reports["figures"]["final_central"]
    lines = []
    lines.append("% Auto-generated by BFL/export_latex_tables.py")
    lines.append(
        "% Threshold: "
        + fmt(reports["threshold"]["threshold"], 5)
        + " ("
        + str(reports["threshold"]["samples"])
        + " benign records)"
    )
    lines.append(
        "% Selected sigma: " + str(reports["sigma_selection"]["selected"]["sigma"])
    )
    lines.append("")
    lines.append("\\begin{table}[H]")
    lines.append("\\centering")
    lines.append(
        "\\caption{Detection performance under the frozen threshold ($V_{th}=0.013$) and the near-threshold weight perturbation $\\sigma^*=0.005$. Values are mean $\\pm$ standard deviation over five independent seeds; TPR/FPR are computed over validator ratings, and ``aggregated'' is the fraction of malicious updates applied to the global model.}"
    )
    lines.append("\\label{tab:detection}")
    lines.append("\\begin{tabular}{lccc}")
    lines.append("\\toprule")
    lines.append("Condition & TPR & Benign FPR & Malicious updates aggregated \\\\")
    lines.append("\\midrule")
    for ratio, label in RATIOS.items():
        for method, method_label in METHODS.items():
            tag = f"clean_{method}" if ratio == 0 else f"nm{ratio}_{method}"
            row = detection.get(tag)
            if row is None:
                continue
            tpr = f"{row['pooled_tpr']:.3f}" if row["pooled_tpr"] is not None else "--"
            fpr = f"{row['pooled_fpr']:.4f}" if row["pooled_fpr"] is not None else "--"
            agg = (
                f"{row['pooled_malicious_applied_rate'] * 100:.1f}\\%"
                if row["pooled_malicious_applied_rate"] is not None
                else "--"
            )
            lines.append(f"{label} {method_label} & {tpr} & {fpr} & {agg} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")
    lines.append("\\begin{table}[H]")
    lines.append("\\centering")
    lines.append(
        "\\caption{Final global $\\epsilon$-prediction loss (round 100, mean $\\pm$ std over seeds) and FID (2000 generated samples vs. 10{,}000 real test images).}"
    )
    lines.append("\\label{tab:loss-fid}")
    lines.append("\\begin{tabular}{lcc}")
    lines.append("\\toprule")
    lines.append("Condition & $\\epsilon$-loss & FID \\\\")
    lines.append("\\midrule")
    for ratio, label in RATIOS.items():
        for method, method_label in METHODS.items():
            tag = f"clean_{method}" if ratio == 0 else f"nm{ratio}_{method}"
            loss = final_federated.get(tag)
            fid_entry = fid.get(tag)
            lines.append(
                f"{label} {method_label} & {pm(loss, 4)} & {pm(fid_entry, 1)} \\\\"
            )
    lines.append("\\midrule")
    loss = final_central.get("tra_clean")
    fid_entry = fid.get("tra_clean")
    lines.append(
        f"Centralized (clean, 34 epochs) & {pm(loss, 4)} & {pm(fid_entry, 1)} \\\\"
    )
    for ratio, tag in [
        (1, "tra_contam_nm1"),
        (3, "tra_contam_nm3"),
        (6, "tra_contam_nm6"),
    ]:
        loss = final_central.get(tag)
        fid_entry = fid.get(tag)
        lines.append(
            f"Centralized (contaminated {RATIOS[ratio]}) & {pm(loss, 4)} & {pm(fid_entry, 1)} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")
    lines.append("\\begin{table}[H]")
    lines.append("\\centering")
    lines.append(
        "\\caption{Staged cost of one communication round under the evaluated configuration. ``Measured'' values are wall-clock measurements from single-tenant runs; ``simulated'' values come from the bandwidth/consensus models and are not measurements of a real deployment.}"
    )
    lines.append("\\label{tab:timing}")
    lines.append("\\begin{tabular}{lcc}")
    lines.append("\\toprule")
    lines.append("Quantity & Value & Source \\\\")
    lines.append("\\midrule")
    reference = timing.get("clean_bc1_def1") or timing.get("clean_bc0_def1") or {}
    quantities = [
        (
            "Worker local training (1 epoch)",
            "worker_local_training_seconds",
            "measured",
        ),
        ("Validator reference update", "validator_reference_seconds", "measured"),
        ("Single-update validation", "validation_seconds", "measured"),
        (
            "Model transfer ($\\approx$3.4~MB at 70~KB/s)",
            "modelled_transmission_seconds",
            "simulated",
        ),
        (
            "Block generation (incl. propagation model)",
            "block_generation_seconds",
            "simulated",
        ),
        ("Round wall clock", "round_wall_seconds", "measured"),
    ]
    for label, key, source in quantities:
        entry = reference.get(key)
        value = pm(entry, 2) if entry else "--"
        unit = "" if value == "--" else "~s"
        lines.append(f"{label} & {value}{unit} & {source} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")
    lines.append("\\begin{table}[H]")
    lines.append("\\centering")
    lines.append(
        "\\caption{Detection rate as a function of the weight-noise scale $\\sigma$ (10\\% malicious nodes, three seeds). The frozen operating point is $\\sigma^*$.}"
    )
    lines.append("\\label{tab:sweep}")
    lines.append("\\begin{tabular}{ccc}")
    lines.append("\\toprule")
    lines.append("$\\sigma$ & Detection rate (TPR) & Final $\\epsilon$-loss \\\\")
    lines.append("\\midrule")
    for row in reports["sigma_selection"]["table"]:
        marker = (
            "$^*$"
            if abs(row["sigma"] - reports["sigma_selection"]["selected"]["sigma"])
            < 1e-09
            else ""
        )
        lines.append(f"{row['sigma']:g}{marker} & {fmt(row['tpr_mean'], 3)} & -- \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")
    args.output.write_text("\n".join(lines) + "\n")
    print(f"wrote LaTeX tables to {args.output}")


if __name__ == "__main__":
    main()
